"""Case/config writers for external open-source solvers.

The in-house structured solver produces the reference numbers, and these
writers emit ready-to-run input decks for the standard community tools so
results can be cross-checked in Docker (openfoam/openfoam11-paraview510)
or locally:

* ``write_openfoam_case`` - OpenFOAM Foundation v11 wedge case
  (``foamRun -solver incompressibleFluid``, BirdCarreau blood).
* ``write_su2_cfg`` - SU2 incompressible 2-D axisymmetric config.
* ``write_calculix_inp`` - CalculiX stent-strut structural model (beams).

OpenFOAM/SU2/CalculiX binaries are NOT bundled; running those decks is a
documented follow-up (see README "Reproducibility" and results TBD notes).
"""

from __future__ import annotations

import math
from pathlib import Path

import numpy as np

from .core import BloodProperties, FlowWaveform, StentParams
from .struct_grid import StructGrid

_OPENFOAM_HEADER = r"""/*--------------------------------*- C++ -*----------------------------------*\
| OpenFOAM case auto-generated by stent_hemo (Foundation v11 syntax).            |
\*---------------------------------------------------------------------------*/
"""


def write_openfoam_case(
    grid: StructGrid,
    blood: BloodProperties,
    wf: FlowWaveform,
    case_dir: str | Path,
) -> Path:
    """Write a complete OpenFOAM v11 wedge case (polyMesh + settings).

    Run inside the official image with:
        foamRun -solver incompressibleFluid
    """
    from .mesh_io import write_openfoam_polymesh

    case_dir = Path(case_dir)
    (case_dir / "system").mkdir(parents=True, exist_ok=True)
    (case_dir / "0").mkdir(parents=True, exist_ok=True)
    write_openfoam_polymesh(grid, case_dir)

    r0 = grid.vessel.r0
    u_mean = wf.mean_flow() / (math.pi * r0**2)

    (case_dir / "system" / "controlDict").write_text(
        _OPENFOAM_HEADER
        + f"""FoamFile
{{
    format ascii;
    class dictionary;
    object controlDict;
}}
application     foamRun;
solver          incompressibleFluid;
startFrom       latestTime;
endTime         {1.5 * wf.period:.6g};
deltaT          {wf.period / 800:.6g};
writeControl    timeStep;
writeInterval   100;
purgeWrite      5;
writeFormat     ascii;
writePrecision  7;
timeFormat      general;
runTimeModifiable true;
functions
{{
    wallShearStress
    {{
        type            wallShearStress;
        libs            ("libfieldFunctionObjects.so");
        writeControl    writeTime;
        patches         (wall);
    }}
    yPlus
    {{
        type            yPlus;
        libs            ("libfieldFunctionObjects.so");
        writeControl    writeTime;
    }}
}}
""",
        encoding="utf-8",
    )

    (case_dir / "system" / "fvSchemes").write_text(
        _OPENFOAM_HEADER
        + """FoamFile
{
    format ascii;
    class dictionary;
    object fvSchemes;
}
ddtSchemes
{
    default Euler;
}
gradSchemes
{
    default         Gauss linear;
}
divSchemes
{
    default         none;
    div(phi,U)      Gauss linearUpwind grad(U);
    div(phi,K)      Gauss linear;
}
laplacianSchemes
{
    default         Gauss linear limited 0.5;
}
interpolationSchemes
{
    default         linear;
}
snGradSchemes
{
    default         limited 0.5;
}
""",
        encoding="utf-8",
    )

    (case_dir / "system" / "fvSolution").write_text(
        _OPENFOAM_HEADER
        + """FoamFile
{
    format ascii;
    class dictionary;
    object fvSolution;
}
solvers
{
    p
    {
        solver          PCG;
        preconditioner  DIC;
        tolerance       1e-07;
        relTol          0.01;
    }
    U
    {
        solver          smoothSolver;
        smoother        symGaussSeidel;
        tolerance       1e-08;
        relTol          0.1;
    }
}
PIMPLE
{
    momentumPredictor yes;
    nOuterCorrectors 2;
    nCorrectors      2;
    nNonOrthogonalCorrectors 0;
}
""",
        encoding="utf-8",
    )

    (case_dir / "constant" / "physicalProperties").write_text(
        _OPENFOAM_HEADER
        + f"""FoamFile
{{
    format ascii;
    class dictionary;
    object physicalProperties;
}}
viscosityModel  BirdCarreau;
nuInf           {blood.mu_inf / blood.rho:.6g};
nu0             {blood.mu0 / blood.rho:.6g};
k               {blood.lam:.6g};
n               {blood.n:.6g};
rho             {blood.rho:.6g};
""",
        encoding="utf-8",
    )

    (case_dir / "constant" / "momentumTransport").write_text(
        _OPENFOAM_HEADER
        + """FoamFile
{
    format ascii;
    class dictionary;
    object momentumTransport;
}
simulationType  laminar;
""",
        encoding="utf-8",
    )

    (case_dir / "0" / "U").write_text(
        _OPENFOAM_HEADER
        + f"""FoamFile
{{
    format ascii;
    class volVectorField;
    object U;
}}
dimensions      [0 1 -1 0 0 0 0];
internalField   uniform (0 0 0);
boundaryField
{{
    inlet
    {{
        type            uniformFixedValue;
        uniformValue    constant ({u_mean:.6g} 0 0);
    }}
    outlet
    {{
        type            zeroGradient;
    }}
    wall
    {{
        type            noSlip;
    }}
    wedge_back
    {{
        type            wedge;
    }}
    wedge_front
    {{
        type            wedge;
    }}
}}
""",
        encoding="utf-8",
    )

    (case_dir / "0" / "p").write_text(
        _OPENFOAM_HEADER
        + """FoamFile
{
    format ascii;
    class volScalarField;
    object p;
}
dimensions      [0 2 -2 0 0 0 0];
internalField   uniform 0;
boundaryField
{
    inlet
    {
        type            zeroGradient;
    }
    outlet
    {
        type            fixedValue;
        value           uniform 0;
    }
    wall
    {
        type            zeroGradient;
    }
    wedge_back
    {
        type            wedge;
    }
    wedge_front
    {
        type            wedge;
    }
}
""",
        encoding="utf-8",
    )

    (case_dir / "Allrun").write_text(
        """#!/bin/sh
cd "$(dirname "$0")" || exit 1
foamRun -solver incompressibleFluid | tee log.foamRun
postProcess -func wallShearStress -latestTime | tee log.post
""",
        encoding="utf-8",
    )
    return case_dir


def write_su2_cfg(
    grid: StructGrid,
    blood: BloodProperties,
    wf: FlowWaveform,
    path: str | Path,
) -> Path:
    """Write an SU2 incompressible axisymmetric config next to the mesh."""
    r0 = grid.vessel.r0
    re = blood.rho * wf.mean_flow() / (math.pi * r0 * blood.mu_newtonian)
    u_mean = wf.mean_flow() / (math.pi * r0**2)
    text = f"""% SU2 incompressible laminar axisymmetric case (auto-generated)
% Reference: https://su2code.github.io
SOLVER= INC_NAVIER_STOKES
AXISYMMETRIC= YES
KIND_TURB_MODEL= NONE
INC_DENSITY_MODEL= CONSTANT
MATH_PROBLEM= DIRECT
RESTART_SOL= NO

INC_DENSITY= {blood.rho:.6g}
INC_VISCOSITY= {blood.mu_newtonian:.6g}
INC_ENERGY_EQ= NO

MACH_NUMBER_LIMITER= NO
CONV_METHOD= JST
TIME_DISCRE_FLOW= EULER_IMPLICIT
RELAX_FACTOR_FLOW= 0.8

MESH_FILENAME= mesh_lumen.su2
MESH_FORMAT= SU2
MESH_LEVELS= 0

MARKER_INLET= INLET
MARKER_OUTLET= OUTLET
MARKER_WALL= WALL

INC_INLET_DENSITY= {blood.rho:.6g}
INC_INLET_VELOCITY= ({u_mean:.6g}, 0.0, 0.0)
INC_OUTLET_PRESSURE= 0.0

% Reynolds number at reference conditions: {re:.1f}
BC_INLET_TYPE= VELOCITY_INLET
BC_OUTLET_TYPE= PRESSURE_OUTLET

ITER= 20000
CONV_FIELD= RMS_VELOCITY
CONV_RESIDUAL_MINVAL= -12
CONV_STARTITER= 1000
"""
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text(text, encoding="utf-8")
    return path


def write_calculix_inp(
    stent: StentParams,
    path: str | Path,
    pressure_pa: float = 8.0e5,
) -> Path:
    """Write a CalculiX (.inp) stent-strut expansion model.

    Simplified documented model: one crown of the stent ring idealized as a
    curved beam (B31 elements) between two crowns, with an internal pressure
    converted to a radial line load. Full 3-D strut CFD-FSI coupling is a
    documented follow-up; this file demonstrates the structural workflow
    (material, static step, contact-free expansion estimate).
    """
    # zigzag crown: 7 crowns -> strut spans half pitch along x, amplitude r0
    span = stent.ring_pitch / 2.0
    n_el = 20
    # sinusoidal strut centerline in the (x, y) plane, unit depth in z
    xs = np.linspace(0.0, span, n_el + 1)
    ys = np.sin(np.pi * xs / span) * (stent.ring_pitch * 0.25)
    lines = ["*HEADING", "Stent strut expansion - simplified beam model"]
    lines.append("*NODE, NSET=NNODE")
    for i, (x, y) in enumerate(zip(xs, ys, strict=False), 1):
        lines.append(f"{i}, {x:.6g}, {y:.6g}, 0.0")
    lines.append("*ELEMENT, TYPE=B31, ELSET=ESTRUT")
    for i in range(1, n_el + 1):
        lines.append(f"{i}, {i}, {i + 1}")
    lines.append("*BEAM SECTION, ELSET=ESTRUT, MATERIAL=STEEL316L, SECTION=RECT")
    a = stent.strut_thickness
    b_sec = stent.strut_width
    lines.append(f"{a:.6g}, {b_sec:.6g}")
    lines.append("0.0, 0.0, 1.0")
    lines.append("*MATERIAL, NAME=STEEL316L")
    lines.append("*ELASTIC")
    lines.append("193.0E9, 0.3")
    lines.append("*DENSITY")
    lines.append("8000.0")
    lines.append("*BOUNDARY")
    lines.append("1, 1, 6")
    lines.append(f"{n_el + 1}, 3, 6")
    lines.append("*STEP")
    lines.append("*STATIC")
    lines.append("0.1, 1.0, 0.001, 0.1")
    # radial pressure -> equivalent transverse line load on the beam
    # q = p * (t * w) per unit length (projected area of the strut face)
    q = pressure_pa * stent.strut_thickness
    lines.append("*DLOAD")
    lines.append(f"ESTRUT, P, {-q:.6g}")
    lines.append("*NODE FILE")
    lines.append("U")
    lines.append("*EL FILE")
    lines.append("S, E")
    lines.append("*END STEP")
    path = Path(path)
    path.parent.mkdir(parents=True, exist_ok=True)
    path.write_text("\n".join(lines) + "\n", encoding="utf-8")
    return path
